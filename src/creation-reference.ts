const rules = "https://www.dndbeyond.com/sources/dnd/basic-rules-2014/";
export type RuleEntry = {
  name: string;
  english: string;
  text: string;
  source: string;
};
function entry(
  section: string,
  name: string,
  english: string,
  text: string,
): RuleEntry {
  return { name, english, text, source: rules + section };
}
function race(name: string, english: string, text: string) {
  return entry("races", name, english, text);
}
